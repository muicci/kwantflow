import { PDFDocument } from 'pdf-lib';
import { beforeEach, describe, expect, it, vi } from 'vitest';

const invokeMock = vi.fn();
const readVaultFileMock = vi.fn();
const generateQuotePdfBytesMock = vi.fn();
const getCachedQuotePdfPackageMock = vi.fn();
const setCachedQuotePdfPackageMock = vi.fn();

vi.mock('@tauri-apps/api/core', () => ({
	invoke: invokeMock
}));

vi.mock('./assets', () => ({
	readVaultFile: readVaultFileMock
}));

vi.mock('./quote-pdf-document', () => ({
	generateQuotePdfBytes: generateQuotePdfBytesMock,
	getCachedQuotePdfPackage: getCachedQuotePdfPackageMock,
	setCachedQuotePdfPackage: setCachedQuotePdfPackageMock
}));

describe('pdf export service', () => {
	function buildPayload() {
		return {
			rfq_number: 'RFQ-1001',
			contact_name: 'Arcwell Property Group',
			contact: null,
			project_name: 'L7 Tenancy Refresh',
			business: {
				name: 'Kwantflow Pty Ltd',
				businessIdLabel: 'ABN',
				businessIdValue: null,
				taxIdLabel: 'GST',
				taxIdValue: null,
				taxDisplayLabel: 'GST',
				taxRatePercentage: 10,
				address: null,
				contactName: null,
				contactEmail: null,
				contactPhone: null,
				currencyCode: 'AUD',
				dateFormat: 'en-AU',
				languageLocale: 'en-AU',
				numberLocale: 'en-AU'
			},
			option_label: 'Base scope',
			lead_time: '4 to 6 weeks',
			notes: null,
			line_items: [],
			subtotal: 0,
			gst: 0,
			total: 0,
			issued_date: '15/03/2026',
			valid_until_date: '14/04/2026'
		};
	}

	beforeEach(() => {
		vi.clearAllMocks();
		invokeMock.mockReset();
		readVaultFileMock.mockReset();
		generateQuotePdfBytesMock.mockReset();
		getCachedQuotePdfPackageMock.mockReset();
		setCachedQuotePdfPackageMock.mockReset();
	});

	async function createMinimalPdfBytes(label: string): Promise<Uint8Array> {
		const pdfDoc = await PDFDocument.create({ updateMetadata: false });
		const page = pdfDoc.addPage([200, 200]);
		page.drawText(label, { x: 24, y: 120, size: 18 });
		return await pdfDoc.save({ addDefaultPage: false, useObjectStreams: false });
	}

	it('reuses the same generated package bytes for preview parity and save operations without sharing the same view', async () => {
		const { generateQuotePackage, getQuotePackagePreview } = await import('./pdf-export');
		const payload = buildPayload();
		const cachedBytes = Uint8Array.from([1, 2, 3, 4]);

		getCachedQuotePdfPackageMock.mockReturnValue(cachedBytes);
		const preview = await getQuotePackagePreview(payload, []);

		expect(preview.bytes).toEqual(cachedBytes);
		expect(preview.bytes).not.toBe(cachedBytes);
		expect(preview.attachmentOutcomes).toEqual([]);
		expect(preview.warnings).toEqual([]);

		await generateQuotePackage(payload, []);

		expect(invokeMock).toHaveBeenCalledWith('save_quote_pdf', {
			rfqNumber: 'RFQ-1001',
			bytes: [1, 2, 3, 4],
			openFile: true
		});
		expect(generateQuotePdfBytesMock).not.toHaveBeenCalled();
	});

	it('returns fresh copies of newly generated bytes for repeated preview requests', async () => {
		const { getQuotePackagePreview } = await import('./pdf-export');
		const payload = { ...buildPayload(), rfq_number: 'RFQ-1002' };
		const generatedBytes = Uint8Array.from([5, 6, 7, 8]);

		getCachedQuotePdfPackageMock.mockReturnValueOnce(undefined).mockReturnValueOnce(generatedBytes);
		generateQuotePdfBytesMock.mockResolvedValue(generatedBytes);

		const firstPreview = await getQuotePackagePreview(payload, []);
		const secondPreview = await getQuotePackagePreview(payload, []);

		expect(firstPreview.bytes).toEqual(generatedBytes);
		expect(secondPreview.bytes).toEqual(generatedBytes);
		expect(firstPreview.bytes).not.toBe(generatedBytes);
		expect(secondPreview.bytes).not.toBe(generatedBytes);
	});

	it('appends selected drawing PDFs after the generated quote document', async () => {
		const { getQuotePackagePreview } = await import('./pdf-export');
		const payload = buildPayload();

		getCachedQuotePdfPackageMock.mockReturnValue(undefined);
		generateQuotePdfBytesMock.mockResolvedValue(await createMinimalPdfBytes('quote'));
		readVaultFileMock.mockResolvedValue(await createMinimalPdfBytes('drawing'));

		const preview = await getQuotePackagePreview(payload, [
			{
				file_id: 'file-1',
				file_name: 'Drawing A.pdf',
				file_path: 'workspace/project-1/drawing-a.pdf'
			}
		]);

		expect(generateQuotePdfBytesMock).toHaveBeenCalledWith(payload);
		expect(readVaultFileMock).toHaveBeenCalledWith('workspace/project-1/drawing-a.pdf');
		expect(preview.attachmentOutcomes).toEqual([
			{
				file_id: 'file-1',
				file_name: 'Drawing A.pdf',
				status: 'appended',
				reason: null
			}
		]);
		expect(preview.warnings).toEqual([]);
	});

	it('returns an omitted attachment outcome and warning when a selected pdf cannot be appended', async () => {
		const { getQuotePackagePreview } = await import('./pdf-export');
		const payload = buildPayload();

		getCachedQuotePdfPackageMock.mockReturnValue(undefined);
		generateQuotePdfBytesMock.mockResolvedValue(await createMinimalPdfBytes('quote'));
		readVaultFileMock.mockRejectedValue(new Error('missing file'));

		const preview = await getQuotePackagePreview(payload, [
			{
				file_id: 'file-2',
				file_name: 'Missing Drawing.pdf',
				file_path: 'workspace/project-1/missing-drawing.pdf'
			}
		]);

		expect(preview.attachmentOutcomes).toEqual([
			{
				file_id: 'file-2',
				file_name: 'Missing Drawing.pdf',
				status: 'omitted',
				reason: 'Could not read or append the selected PDF.'
			}
		]);
		expect(preview.warnings).toEqual(['1 selected PDF attachment was omitted from the package.']);
	});
});
